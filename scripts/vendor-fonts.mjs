// Regenerates src/frontend/css/fonts.css: the Vazirmatn variable font (SIL OFL 1.1),
// embedded as data URIs so the app looks the same on every machine and never
// depends on a font being installed or on how the webview serves files.
//   node scripts/vendor-fonts.mjs            (needs network once, for `npm pack`)
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '5.3.0';
const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.join(here, '..');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'vazirmatn-'));

execFileSync('npm', ['pack', `@fontsource-variable/vazirmatn@${VERSION}`, '--silent'], { cwd: tmp, stdio: ['ignore', 'ignore', 'inherit'] });
const tgz = fs.readdirSync(tmp).find((f) => f.endsWith('.tgz'));
execFileSync('tar', ['xzf', tgz], { cwd: tmp });
const pkg = path.join(tmp, 'package');

// unicode-range per subset comes from the package's own stylesheet
const source = fs.readFileSync(path.join(pkg, 'wght.css'), 'utf8');
const faces = [...source.matchAll(/\/\* (vazirmatn-[\w-]+-wght-normal) \*\/[\s\S]*?unicode-range:\s*([^;]+);/g)].map((m) => ({ name: m[1], range: m[2] }));
if (faces.length !== 3) throw new Error(`expected 3 subsets, found ${faces.length}`);

let css = `/* Vazirmatn variable (v${VERSION}) — Copyright 2015 The Vazirmatn Project Authors,
   SIL Open Font License 1.1 (licenses/Vazirmatn-OFL.txt). Generated by scripts/vendor-fonts.mjs. */\n`;
for (const f of faces) {
  const data = fs.readFileSync(path.join(pkg, 'files', `${f.name}.woff2`)).toString('base64');
  css += `\n@font-face {\n  font-family: "Vazirmatn Variable";\n  font-style: normal;\n  font-display: swap;\n  font-weight: 100 900;\n  src: url(data:font/woff2;base64,${data}) format("woff2");\n  unicode-range: ${f.range};\n}\n`;
}
fs.writeFileSync(path.join(repo, 'src/frontend/css/fonts.css'), css);
fs.mkdirSync(path.join(repo, 'licenses'), { recursive: true });
fs.copyFileSync(path.join(pkg, 'LICENSE'), path.join(repo, 'licenses/Vazirmatn-OFL.txt'));
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`wrote src/frontend/css/fonts.css (${(css.length / 1024).toFixed(0)} KB) and licenses/Vazirmatn-OFL.txt`);
